-- ============================================================================
-- V2：为 voyage 增加航线级「是否经运河」标记
--
-- 来源：决策 C-18（docs/DECISIONS.md），由领域模型能力探针 7 的实测发现触发。
--
-- 解决什么问题
-- ----------------------------------------------------------------------------
-- V1 里「是否经运河」只能靠 port.is_canal_node 推断，但那是**港口**属性，
-- 回答不了「这条航线是否穿越运河」。实测矛盾正是这么来的：
-- 有 56 个航次（743 票）**两端都不是运河节点**，却被收了过闸费——
-- 于是文档里的口径互相打架（端点口径 97.67% vs 过闸费覆盖率 100%）。
--
-- 加上本字段后：
--   ① 「哪些航线经运河 / 不经运河」成为航线级可直接回答的问题；
--   ② 过闸费改为**只在 via_canal 为真时收取**，费用数据与航道事实自洽，
--      上述矛盾消失（代价是过闸费占比由 29.05% 下降，见 DECISIONS.md C-18）。
--
-- 取值口径（方案 1，用户已确认）
-- ----------------------------------------------------------------------------
--   via_canal = true  当且仅当  起点港 或 终点港 属于运河节点
--                          （即 port.is_canal_node = true）
--
-- ⚠️ 这是**仿真数据的简化口径**，不是真实航运的航道几何判定：
--    真实的「是否经运河」取决于航线是否穿过运河航道，而非端点属性。
--    若将来要精确判定，应改为航段路径表（当时的方案 B），届时本字段
--    的语义需一并重新定义，属于要重新与用户确认的事项。
--
-- 幂等性
-- ----------------------------------------------------------------------------
-- 本文件写成可重复执行（IF NOT EXISTS），便于在不重建库的情况下补列。
-- 但**数据仍须重新生成**才能填上正确取值，故完整流程仍需 -Recreate。
-- ============================================================================

ALTER TABLE voyage
    ADD COLUMN IF NOT EXISTS via_canal BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN voyage.via_canal IS
    '该航次航线是否经平陆运河。口径：起点港或终点港为运河节点（port.is_canal_node）即为真。属仿真数据简化口径，非航道几何判定。';

-- 索引取舍说明（刻意为之，不要"顺手"改成普通 btree）
-- ----------------------------------------------------------------------------
-- 本列取值高度倾斜：实测约 97.67% 为 true、2.33% 为 false。
-- 在这么倾斜的列上建普通 btree，绝大多数查询（筛 true）走索引反而不如全表扫描，
-- 规划器也不会选它。真正需要索引的是**少数派**查询——「列出不经运河的航线」，
-- 因此建**部分索引**只覆盖 via_canal = false 的行。
-- 同理，聚合类查询（count(*) FILTER (WHERE via_canal)）本来就走 seq scan，无需索引。
CREATE INDEX IF NOT EXISTS idx_voyage_not_via_canal
    ON voyage (origin_port, dest_port)
    WHERE via_canal = false;
